import assert from 'node:assert/strict';
import {validateQuestion,gradeQuestion,missedItems,numericValue,answerText} from './src/question-types.js';
import {specFromDraft,draftFromSpec} from './src/question-variants.js';
import {pictureLabel,isPictureLabel} from './src/question-variants.js';
const make=(type,extra={})=>validateQuestion({prompt:'Question?',answer:'Yes',type,...extra});
assert.equal(make('true_false',{answer:'false'}).answer,'False');
assert.equal(gradeQuestion(make('true_false',{answer:'True'}),'False'),false);
assert.throws(()=>make('true_false'),/True or False/);
const multi=make('multi_select',{options:['A','B','C'],correctAnswers:['A','C']});
assert.equal(multi.answer,'A; C');assert.equal(gradeQuestion(multi,['C','A']),true);
assert.equal(gradeQuestion(multi,['A']),false);assert.equal(gradeQuestion(multi,['A','B','C']),false);
assert.throws(()=>make('multi_select',{options:['A','B'],correctAnswers:['C']}),/match/);
assert.throws(()=>make('single_choice',{options:['A','A'],answer:'A'}),/different/);
assert.throws(()=>make('single_choice',{options:['A','B'],answer:'C'}),/match/);
const number=make('numeric',{answer:'-3.14',numericTolerance:.01});
assert.equal(gradeQuestion(number,'-3.13'),true);assert.equal(gradeQuestion(number,'3.14'),false);
assert.equal(gradeQuestion(number,'-3.12'),false);assert.equal(gradeQuestion(number,''),false);
for(const invalid of ['Infinity','NaN','0xff','3 kg',' ',true])assert.equal(numericValue(invalid),null);
assert.equal(gradeQuestion(make('numeric',{answer:'1000'}),'1e3'),true);
assert.throws(()=>make('numeric',{answer:'5',numericTolerance:-1}),/tolerance/);
assert.equal(gradeQuestion(make('short_answer',{answer:'Tokyo'}),' tokyo! '),true);
const bank=[{id:'a',prompt:'Edited prompt'},{id:'b'},{id:'c'}];
assert.deepEqual(missedItems([{knowledge_id:'a',correct:false},{knowledge_id:'a',correct:false},{knowledge_id:'b',correct:true},{knowledge_id:'deleted',correct:false}],bank),[bank[0]]);
assert.deepEqual(missedItems([{knowledge_id:'a',correct:true}],bank),[]);
const pic='data:image/png;base64,iVBORw0KGgo=';
assert.equal(make('short_answer',{prompt:'',image:pic}).prompt,'');
assert.equal(make('single_choice',{prompt:'  ',image:pic,options:['A','B'],answer:'A'}).prompt,'');
assert.throws(()=>make('short_answer',{prompt:''}),/question/i);
assert.throws(()=>make('fill_blank',{prompt:'',image:pic}));
assert.equal(make('flashcard',{answer:'',answerImage:pic}).answer,'');
assert.throws(()=>make('flashcard',{answer:''}));
assert(isPictureLabel(pictureLabel(3))&&isPictureLabel('Picture B')&&!isPictureLabel('Picture of a cat')&&!isPictureLabel(''));
const tone='data:audio/wav;base64,UklGRiQAAABXQVZFZm10IBAAAAABAAEAQB8AAEAfAAABAAgAZGF0YQAAAAA=';
const named=make('audio_name',{prompt:'',audio:tone,answer:'Jana Gana Mana'});
assert.equal(named.prompt,'Name this sound.');assert.equal(gradeQuestion(named,'jana gana mana'),true);assert.equal(gradeQuestion(named,'God Save the King'),false);
assert.throws(()=>make('audio_name',{answer:'X'}));
const clips=[{label:'India',audio:tone},{label:'France',audio:tone}];
assert.equal(gradeQuestion(make('audio_choice',{clips,answer:'India'}),'India'),true);
assert.equal(gradeQuestion(make('audio_order',{clips}),['France','India']),false);
assert.equal(gradeQuestion(make('audio_order',{clips}),['India','France']),true);
const tap=make('image_tap',{prompt:'',image:pic,spots:[{x:20,y:30,label:'France'}]});
assert.equal(gradeQuestion(tap,{x:24,y:33}),true);assert.equal(gradeQuestion(tap,{x:80,y:80}),false);assert.equal(answerText(tap),'France');
const labels=make('image_label',{image:pic,spots:[{x:10,y:10,label:'Heart'},{x:70,y:40,label:'Lung'}]});
assert.equal(gradeQuestion(labels,['Heart','Lung']),true);assert.equal(gradeQuestion(labels,['Lung','Heart']),false);
assert.equal(gradeQuestion(make('odd_one_out',{options:['Apple','Banana','Car'],answer:'Car'}),'Car'),true);
assert.throws(()=>make('odd_one_out',{options:['A','B'],answer:'A'}));
const groups=make('categorize',{groups:[{name:'Europe',items:['France']},{name:'Asia',items:['Japan']}]});
assert.equal(gradeQuestion(groups,[{item:'Japan',group:'Asia'},{item:'France',group:'Europe'}]),true);
assert.equal(gradeQuestion(groups,[{item:'Japan',group:'Europe'},{item:'France',group:'Asia'}]),false);
assert.equal(gradeQuestion(make('build_answer',{sequence:['Jana','Gana'],options:['Gama']}),['Jana','Gana']),true);
assert.equal(gradeQuestion(make('two_step',{steps:[{prompt:'Name?',answer:'Jana Gana Mana'},{prompt:'Country?',answer:'India'}]}),['Jana Gana Mana','India']),true);
assert.equal(make('dictation',{audio:tone,answer:'Hello'}).fuzzy,false);
const roundTrip=draftFromSpec(make('timeline',{sequence:['1947 · Independence','1950 · Republic']}));
assert.equal(specFromDraft(roundTrip).sequence.join('|'),'1947 · Independence|1950 · Republic');
console.log('PASS: exact multi-select sets, signed numeric/tolerance grading, validation, picture-only questions and answers, existing text grading, retry deduplication and deleted/edited questions, and the new sound, picture and arrange types.');
